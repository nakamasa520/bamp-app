CREATE TABLE IF NOT EXISTS members(
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, reading TEXT DEFAULT '', grp TEXT DEFAULT '', role TEXT DEFAULT '',
  captain_of TEXT, car_out TEXT DEFAULT '', car_in TEXT DEFAULT '', grade TEXT DEFAULT '',
  att1 TEXT DEFAULT '', att2 TEXT DEFAULT '', sort INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS slots(day INTEGER NOT NULL, idx INTEGER NOT NULL, start TEXT NOT NULL, end TEXT, PRIMARY KEY(day,idx));
CREATE TABLE IF NOT EXISTS entries(
  member_id INTEGER NOT NULL, day INTEGER NOT NULL, idx INTEGER NOT NULL, activity TEXT DEFAULT '', note TEXT DEFAULT '',
  updated_at TEXT, PRIMARY KEY(member_id,day,idx));
CREATE TABLE IF NOT EXISTS comments(
  id INTEGER PRIMARY KEY AUTOINCREMENT, member_id INTEGER, text TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS meta(key TEXT PRIMARY KEY, value TEXT);
