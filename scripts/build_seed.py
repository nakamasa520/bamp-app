#!/usr/bin/env python3
"""工程表.xlsx -> seed/real.sql + seed/real.json
   --anonymize : 氏名をダミー化した seed/sample.sql を出力（公開リポジトリ用）
使い方: python3 scripts/build_seed.py data/schedule.xlsx
"""
import sys, json, re, openpyxl
from openpyxl.utils import column_index_from_string as ci

SRC = next((a for a in sys.argv[1:] if not a.startswith('--')), 'data/schedule.xlsx')
ANON = '--anonymize' in sys.argv

# 工程表の列 -> スロット（開始, 終了）。終了 None は「以降」
DAY24 = [('I','10:15','11:00'),('J','11:00','12:00'),('K','12:00','12:45'),('L','12:45','13:00'),
         ('M','13:00','14:30'),('N','14:30','14:45'),('O','14:45','16:15'),('P','16:15','16:30'),
         ('Q','16:30','17:45'),('R','17:45','18:00'),('S','18:00','18:30'),('T','18:30','20:00'),('U','20:00',None)]
# AE 列はヘッダが「18:00」だが、24日 R 列と同じ役割(17:45-18:00)と解釈
DAY25 = [('W','10:00','12:00'),('X','12:00','12:45'),('Y','12:45','13:00'),('Z','13:00','14:30'),
         ('AA','14:30','14:45'),('AB','14:45','16:15'),('AC','16:15','16:30'),('AD','16:30','17:45'),
         ('AE','17:45','18:00'),('AF','18:00',None)]
# 姓の読み（検索補助。画面には出さない）
READ = {'中西':'なかにし','鬼丸':'おにまる','河野':'こうの かわの','池田':'いけだ','小山':'こやま おやま','宮永':'みやなが',
        '山下':'やました','寺本':'てらもと','森':'もり','山根':'やまね','舩原':'ふなはら','髙木':'たかぎ','西村':'にしむら',
        '廣田':'ひろた','福元':'ふくもと','恩田':'おんだ','堀部':'ほりべ','余傳':'よでん','敷田':'しきだ','小野':'おの',
        '野島':'のじま','佐伯':'さえき'}

ws = openpyxl.load_workbook(SRC).active
# 結合セルから group を決める
group = {}
for rng in list(ws.merged_cells.ranges):
    g = ws.cell(rng.min_row, 1).value
    for r in range(rng.min_row, rng.max_row+1): group[r] = g
for r in range(2, ws.max_row+1):
    if ws.cell(r,1).value: group[r] = ws.cell(r,1).value

def v(col, r):
    x = ws[f'{col}{r}'].value
    return None if x is None else str(x).strip()

members, entries = [], []
for r in range(2, ws.max_row+1):
    name = v('E', r)
    if not name: continue
    role = v('B', r) or ''
    grp = group.get(r, '')
    cap = None
    m = re.match(r'Captain-(.+)$', role)
    if m and grp in ('建築', '全体把握'):          # 演出グループの "Captain-Circle" は領域Captainではない
        cap = m.group(1)
    sur = name.split()[0]
    mid = len(members) + 1
    members.append(dict(id=mid, name=name, reading=READ.get(sur, ''), grp=grp, role=role, captain_of=cap,
                        car_out=v('C',r) or '', car_in=v('D',r) or '', grade=v('F',r) or '',
                        att1=v('G',r) or '', att2=v('H',r) or '', sort=mid))
    for day, cols in ((24, DAY24), (25, DAY25)):
        for idx, (c, s, e) in enumerate(cols):
            entries.append(dict(member_id=mid, day=day, idx=idx, activity=v(c, r) or '', note=''))

slots = [dict(day=d, idx=i, start=s, end=e) for d, cols in ((24,DAY24),(25,DAY25)) for i,(c,s,e) in enumerate(cols)]

CARS = {}
if ANON:
    for m in members:
        m['name'] = f"メンバー{m['id']:02d}"; m['reading'] = ''
        for k, tail in (('car_out', '中津駅着'), ('car_in', '中津駅発')):
            v_ = m[k]
            if re.search(r'\d', v_): m[k] = tail
            elif v_.endswith('号'): m[k] = '車' + chr(ord('A') + CARS.setdefault(v_, len(CARS)))
            elif '単独' in v_: m[k] = '単独便'

def q(x): return 'NULL' if x is None else "'" + str(x).replace("'", "''") + "'"
out = ['-- generated by scripts/build_seed.py', 'DELETE FROM entries; DELETE FROM members; DELETE FROM slots; DELETE FROM comments;']
for m in members:
    out.append("INSERT INTO members(id,name,reading,grp,role,captain_of,car_out,car_in,grade,att1,att2,sort) VALUES(%d,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%d);" %
      (m['id'],q(m['name']),q(m['reading']),q(m['grp']),q(m['role']),q(m['captain_of']),q(m['car_out']),q(m['car_in']),q(m['grade']),q(m['att1']),q(m['att2']),m['sort']))
for s in slots:
    out.append("INSERT INTO slots(day,idx,start,end) VALUES(%d,%d,%s,%s);" % (s['day'],s['idx'],q(s['start']),q(s['end'])))
for e in entries:
    out.append("INSERT INTO entries(member_id,day,idx,activity,note) VALUES(%d,%d,%d,%s,'');" % (e['member_id'],e['day'],e['idx'],q(e['activity'])))
out.append("INSERT OR REPLACE INTO meta(key,value) VALUES('version','1');")
name = 'sample' if ANON else 'real'
open(f'seed/{name}.sql','w').write('\n'.join(out)+'\n')
json.dump(dict(members=members, slots=slots, entries=entries), open(f'seed/{name}.json','w'), ensure_ascii=False, indent=1)
print(name, len(members), 'members', len(slots), 'slots', len(entries), 'entries')
print([ (m['name'], m['captain_of']) for m in members if m['captain_of']])
